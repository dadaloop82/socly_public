CREATE TABLE IF NOT EXISTS treasury_health_dismissals (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  issue_key VARCHAR(64) NOT NULL,
  fingerprint VARCHAR(190) NOT NULL DEFAULT '',
  user_id INT UNSIGNED NULL,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
  UNIQUE KEY uq_thd_issue_fp (issue_key, fingerprint),
  KEY idx_thd_user (user_id),
  CONSTRAINT fk_thd_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
