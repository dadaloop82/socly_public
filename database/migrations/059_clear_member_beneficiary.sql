-- A linked member is the counterparty: a free-text beneficiary typed before the member was
-- selected is stale and must not be stored next to member_id.
UPDATE treasury_movements
   SET beneficiary = NULL
 WHERE member_id IS NOT NULL
   AND beneficiary IS NOT NULL
   AND beneficiary <> '';
